// Regenerates js/real-seed.js from the real LedgerPro book.
//
// Wiring (dev mode only — never set in packaged builds):
//   LEDGERPRO_DEV=1 → main.js app:flags → preload (window.ledger.devSeed)
//   → js/data.js seedSampleData() returns this snapshot as the demo seed,
//     so launching `npm run dev:real` on an empty database boots the real book.
//
// The emitted rows mirror db.load()'s in-memory mapping exactly (camelCase
// fields, liquid as boolean, created_at → createdAt), so the seeded books are
// byte-for-byte what a disk-backed load would hand to the Store.
//
// Run:  npm run seed:regen   (= ELECTRON_RUN_AS_NODE=1 electron scripts/export-real-seed.js)
// The output is prettier-formatted on the spot so `format:check` stays green.
//
// Note: better-sqlite3 is compiled against Electron's ABI, so this must run
// under Electron's Node (ELECTRON_RUN_AS_NODE=1), not the system Node.

const { execFileSync } = require('child_process');
const os = require('os');
const path = require('path');
const fs = require('fs');

// better-sqlite3 is built for the Electron runtime ABI (see rebuild:electron).
const Database = require(path.join(__dirname, '..', 'node_modules', 'better-sqlite3'));

const DEFAULT_DB = path.join(
  process.env.HOME || os.homedir(),
  'Library',
  'Application Support',
  'LedgerPro',
  'ledger.db'
);
const OUT = path.join(__dirname, '..', 'js', 'real-seed.js');

const src = process.argv[2] || DEFAULT_DB;
if (!fs.existsSync(src)) {
  console.error(`export-real-seed: source database not found: ${src}`);
  process.exitCode = 1;
  process.exit(1);
}

// Snapshot to a temp dir first: reading the live WAL database in place can
// race with a checkpoint if the app is running. db + -wal + -shm copied in
// one shot give a coherent (post-wal) state.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ledgerpro-seed-'));
for (const ext of ['', '-wal', '-shm']) {
  const from = src + ext;
  if (fs.existsSync(from)) fs.copyFileSync(from, path.join(tmp, 'ledger.db' + ext));
}
const db = new Database(path.join(tmp, 'ledger.db'), { readonly: true });

const accounts = db
  .prepare(
    `SELECT id, name, group_name, type, category, liquid, opening FROM accounts
     ORDER BY CASE group_name
       WHEN 'Assets' THEN 1
       WHEN 'Liabilities' THEN 2
       WHEN 'Income' THEN 3
       WHEN 'Expenses' THEN 4
       ELSE 5
     END, name COLLATE NOCASE ASC`
  )
  .all()
  .map((r) => ({
    id: r.id,
    name: r.name,
    group: r.group_name,
    type: r.type,
    category: r.category || '',
    liquid: r.liquid === 1,
    opening: r.opening,
  }));

const vouchers = db
  .prepare(
    'SELECT id, no, date, type, dr, cr, amount, narration, created_at FROM vouchers ORDER BY date, created_at, id'
  )
  .all()
  .map((r) => ({
    id: r.id,
    no: r.no,
    date: r.date,
    type: r.type,
    dr: r.dr,
    cr: r.cr,
    amount: r.amount,
    narration: r.narration,
    createdAt: r.created_at || '',
  }));
db.close();
for (const ext of ['', '-wal', '-shm']) {
  try {
    fs.unlinkSync(path.join(tmp, 'ledger.db' + ext));
  } catch (e) {
    /* ignore */
  }
}
fs.rmSync(tmp, { recursive: true, force: true });

if (!accounts.length) {
  console.error('export-real-seed: source database has no accounts — refusing to write an empty seed');
  process.exitCode = 1;
  process.exit(1);
}

const doc = {
  meta: {
    generatedAt: new Date().toISOString(),
    source: src,
    accounts: accounts.length,
    vouchers: vouchers.length,
    range: vouchers.length ? `${vouchers[0].date} .. ${vouchers[vouchers.length - 1].date}` : '',
  },
  accounts,
  vouchers,
};

const body = `// Generated by scripts/export-real-seed.js — DO NOT EDIT by hand.
// Snapshot of the real ledger (${doc.meta.range}) used as the dev-mode demo
// seed when LEDGERPRO_DEV=1 (npm run dev:real). Regenerate with:
//   npm run seed:regen
globalThis.LEDGERPRO_REAL_SEED = ${JSON.stringify(doc, null, 2)};
`;

fs.writeFileSync(OUT, body);

// Format immediately: package.json's format list covers js/*.js.
try {
  execFileSync(path.join(__dirname, '..', 'node_modules', '.bin', 'prettier'), ['--write', OUT], {
    stdio: 'ignore',
  });
} catch (e) {
  console.error('export-real-seed: prettier failed to format the output (file still written)');
}

console.log(
  `export-real-seed: wrote js/real-seed.js — ${accounts.length} accounts, ${vouchers.length} vouchers (${doc.meta.range})`
);
